// Sınıf Butonlarını Oluşturma
    function renderClassButtons() {
        const btnContainer = document.getElementById('class-buttons');
        /* Bu dosya index.html'de yalnızca VERİ kaynağı (educationData) olarak da
           yükleniyor; orada #class-buttons yoktur, sessizce çıkılır. */
        if (!btnContainer) return;
        /* İmam Hatip kartlarından "?sinif=N" ile gelince o sınıf açılsın
           (ortak dosya, kart kategorize eder). Geçersizse eski davranış. */
        var _sinifParam = new URLSearchParams(location.search).get('sinif');
        const lastClass = (_sinifParam && educationData[_sinifParam])
            ? _sinifParam : (localStorage.getItem('lastSelectedClass') || "10");
        
        Object.keys(educationData).forEach(classLevel => {
            const btn = document.createElement('button');
            btn.className = 'class-btn';
            btn.innerText = classLevel + ". Sınıf";
            
            // 10. Sınıf butonu yeşil
           if (classLevel === "10" || classLevel === "9" || classLevel === "7") {
                btn.classList.add('hazir-sinif');
            }

            btn.onclick = () => selectClass(classLevel, btn, true);

            if (classLevel === lastClass) {
                btnContainer.appendChild(btn);
                selectClass(classLevel, btn); 
            } else {
                btnContainer.appendChild(btn);
            }
        });
    }

    // Sınıf Seçildiğinde İçeriği Göster
    /* kullaniciSecti: sadece kullanici bir sinifa tikladiginda sayfayi asagi
       kaydiriyoruz. Ilk aciliste kaydirmiyoruz ki baslik gorunsun. */
    function selectClass(level, btnElement, kullaniciSecti) {
        localStorage.setItem('lastSelectedClass', level);
        document.querySelectorAll('.class-btn').forEach(b => b.classList.remove('active'));
        btnElement.classList.add('active');

        const container = document.getElementById('unit-container');
        container.innerHTML = '';

        const units = educationData[level];

        units.forEach(unit => {
            const unitCard = document.createElement('div');
            unitCard.className = 'unit-card';
            
let lessonsHTML = unit.lessons.map(lesson => {
    const statusClass = lesson.aktif ? 'hazir' : '';
    const nameSpan = lesson.name ? `<span class="lesson-name">${lesson.name}</span>` : '<span class="lesson-name" style="display:none"></span>';
    
    return `
    <div class="lesson-item">
        <div class="lesson-info">
            ${nameSpan}
        </div>
        <div class="btn-group">
            <a href="${lesson.simultaneUrl}" class="action-btn btn-simultane ${statusClass}">🎧 SİMÜLTANE</a>
        </div>
    </div>
`}).join('');

            unitCard.innerHTML = `
                <div class="unit-header">${unit.unitName}</div>
                <div class="lesson-list">${lessonsHTML}</div>
            `;
            container.appendChild(unitCard);
        });

        if (kullaniciSecti) {
            window.scrollTo({ top: headerHeight(), behavior: 'smooth' });
        }
    }

    function headerHeight() {
        return document.querySelector('header').offsetHeight - 50;
    }

    // Başlat
    renderClassButtons();