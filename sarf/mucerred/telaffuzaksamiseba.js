    let activeSet = [], currentStage = 0, startTime, timerInterval, elapsedTime = 0, isPaused = false, raceMode = false, errorMemory = new Set(), selectedCat = "";

    function init() {
        const container = document.getElementById('cat-list');
        aksam.forEach(c => {
            const btn = document.createElement('button');
            btn.className = 'cat-btn'; btn.innerText = c;
            btn.onclick = () => { sfx(600,'sine',0.05); selectedCat = c; showFiils(c); };
            container.appendChild(btn);
        });
    }

    function showFiils(cat) {
        hideHeaderElements();
        const container = document.getElementById('fiil-list');
        container.innerHTML = '';
        verbs[cat].forEach(f => {
            const btn = document.createElement('button');
            btn.className = 'fiil-btn'; btn.innerText = f;
            btn.onclick = () => { sfx(600,'sine',0.05); preparePlay(f); };
            container.appendChild(btn);
        });
        showScreen('screen-fiil');
    }

    function resetTimerVariables() {
    clearInterval(timerInterval); // Mevcut sayacı durdur
    elapsedTime = 0;             // Geçen süreyi sıfırla
    startTime = 0;               // Başlangıç zamanını temizle
    isPaused = false;            // Duraklatma modunu kapat
    document.getElementById('timer-display').textContent = "00:00"; // Ekranı temizle
}

    function preparePlay(fiil) {
    // verbData içinde bu fiil varsa listeyi al, yoksa (hata olmasın diye) aynı kelimeyi 36 kez bas
    if (verbData && verbData[fiil]) {
        activeSet = verbData[fiil];
    } else {
        activeSet = Array(36).fill(fiil);
    }
    
    currentStage = 0; 
    errorMemory.clear(); 
    elapsedTime = 0; 
    raceMode = false;
    showScreen('screen-play'); 
    loadTable();
    
    // UI Elemanlarını göster
    document.getElementById('stage-label').classList.add('ui-visible');
    document.getElementById('chrono-main').style.display = 'block';
}

    function handleChronoClick() {
        if (!raceMode) {
            raceMode = true;
            document.getElementById('chrono-main').classList.add('active');
            document.getElementById('overlay').style.display = 'flex';
            document.getElementById('start-btn-ui').style.display = 'block';
            document.getElementById('countdown-text').style.display = 'none';
        } else { resetRace(); }
    }

    function startCountdown() {
        errorMemory.clear(); currentStage = 0; loadTable();
        document.getElementById('start-btn-ui').style.display = 'none';
        const cd = document.getElementById('countdown-text');
        cd.style.display = 'block';
        let count = 3; cd.innerText = count;
        const interval = setInterval(() => {
            count--;
            if (count > 0) { cd.innerText = count; sfx(400, 'sine', 0.1); }
            else { clearInterval(interval); document.getElementById('overlay').style.display = 'none'; startTimer(); }
        }, 1000);
    }

    function startTimer() {
        document.getElementById('pause-btn').classList.add('ui-visible');
        document.getElementById('timer-display').classList.add('ui-visible');
        document.getElementById('live-total-score').classList.add('ui-visible');
        startTime = Date.now();
        timerInterval = setInterval(() => {
            if (!isPaused) {
                elapsedTime = (Date.now() - startTime) / 1000;
                document.getElementById('timer-display').innerText = elapsedTime.toFixed(2);
                let score = Math.max(0, Math.round(100 - (elapsedTime > 45 ? (elapsedTime-45)*2 : 0) - (errorMemory.size * 2)));
                document.getElementById('live-total-score').innerText = score;
            }
        }, 50);
    }

    function loadTable() {
    const table = document.getElementById('table-view');
    table.innerHTML = '';
    
    // Sayfa aralıkları: Mazi: 0-15, Muzari: 15-30, Emir: 30-36
    const ranges = [[0, 15], [15, 30], [30, 36]];
    const start = ranges[currentStage][0];
    const end = ranges[currentStage][1];
    
    document.getElementById('stage-label').innerText = ["MAZİ", "MUZARİ", "EMİR"][currentStage];

    // Sadece aktif sayfadaki fiilleri filtreleyip ekrana basar
    activeSet.slice(start, end).forEach((w, i) => {
        const absoluteIdx = start + i;
        const div = document.createElement('div');
        div.className = 'cell ' + (Math.floor(i/3) % 2 === 0 ? 'muez-row' : 'mue-row');
        if(errorMemory.has(absoluteIdx)) div.classList.add('error-active');
        div.innerText = w;
        
        div.onclick = function() {
            if (errorMemory.has(absoluteIdx)) {
                errorMemory.delete(absoluteIdx);
                this.classList.remove('error-active');
                sfx(400, 'sine', 0.1); // Düzeltme sesi
            } else {
                errorMemory.add(absoluteIdx);
                this.classList.add('error-active');
                sfx(150, 'sawtooth', 0.2); // Hata sesi
            }
        };
        table.appendChild(div);
    });

    // Alt navigasyon butonları
    document.getElementById('prev-arr').disabled = (currentStage === 0);
    const rArr = document.getElementById('next-arr');
    rArr.innerText = (currentStage === 2) ? "✓" : "❯";
}

    function changeStage(dir) {
        if (currentStage === 2 && dir === 1 && raceMode) { finishRace(); return; }
        currentStage += dir;
        loadTable();
    }

    function finishRace() {
        clearInterval(timerInterval);
        document.getElementById('final-score').innerText = document.getElementById('live-total-score').innerText;
        const errList = document.getElementById('error-list');
        errList.innerHTML = '';
        errorMemory.forEach(idx => {
            const item = document.createElement('div');
            item.className = 'error-item'; item.innerText = activeSet[idx];
            errList.appendChild(item);
        });
        showScreen('screen-result');
        hideHeaderElements();
    }

    function hideHeaderElements() {
        document.getElementById('stage-label').classList.remove('ui-visible');
        document.getElementById('chrono-main').style.display = 'none';
        document.getElementById('pause-btn').classList.remove('ui-visible');
        document.getElementById('timer-display').classList.remove('ui-visible');
        document.getElementById('live-total-score').classList.remove('ui-visible');
    }

