    /* SES SENKRONU                                                      */
    /* ---------------------------------------------------------------- */
    /* Tarayıcı, kullanıcı sayfaya dokunana kadar AudioContext'i ASKIYA
       alıyor. Askıdayken kurulan sesler kaybolmuyor: bağlamın saati
       durduğu için hepsi "sıfır anına" zamanlanıyor ve kullanıcı ilk
       kez dokunduğunda ARKA ARKAYA patlıyor — tık sesleri geç ve toplu
       geliyor. Sayfa açılırken çalan sesler (kendiliğinden yüklenen
       kök, günün kökü vb.) bu yüzden yığılıyordu.
       Çözüm: ilk dokunuştan ÖNCE ses hiç kurulmuyor. Sonrası aynen
       çalışıyor, tek ses gecikmesiz çıkıyor. */
    var etkilesildi = false;
    ['pointerdown', 'keydown', 'touchstart'].forEach(function (t) {
        document.addEventListener(t, function () { etkilesildi = true; }, true);
    });

    function sesKilidi() {
        if (typeof SoundEngine === 'undefined' || SoundEngine._vg) return;
        ['playClick', 'playClose', 'playReset'].forEach(function (ad) {
            var eski = SoundEngine[ad];
            if (typeof eski !== 'function') return;
            SoundEngine[ad] = function () {
                if (!etkilesildi) return;             /* daha dokunulmadı: sessiz */
                return eski.apply(this, arguments);
            };
        });
        SoundEngine._vg = 1;
    }

    /* ---------------------------------------------------------------- */
    /* SES: "BAŞKA VEZİN KALMADI"                                        */
    /* ---------------------------------------------------------------- */
    /* SoundEngine'in kendi sesleri (tık / kapanış / onay) hep TEK vuruş.
       Bu uyarı bilerek ÇİFT ve inen perdeden: kulak onu ötekilerle
       karıştırmasın, "bitti" duyulsun. */
    function vezinBittiSesi() {
        try {
            if (typeof SoundEngine === 'undefined' || !SoundEngine.init) return;
            SoundEngine.init();
            var c = SoundEngine.ctx, t = c.currentTime;
            [[0, 300, 190], [0.14, 210, 120]].forEach(function (v) {
                var o = c.createOscillator(), g = c.createGain();
                o.type = 'sine';
                o.frequency.setValueAtTime(v[1], t + v[0]);
                o.frequency.exponentialRampToValueAtTime(v[2], t + v[0] + 0.10);
                g.gain.setValueAtTime(0, t + v[0]);
                g.gain.linearRampToValueAtTime(0.05, t + v[0] + 0.012);
                g.gain.exponentialRampToValueAtTime(0.001, t + v[0] + 0.12);
                o.connect(g); g.connect(c.destination);
                o.start(t + v[0]); o.stop(t + v[0] + 0.15);
            });
        } catch (e) { /* ses yoksa sessiz geç */ }
    }

    /* Ses kapalı olabilir: son vezin ayrıca iki kez kırmızı çerçeve
       yakıp söndürür. Çerçeve OUTLINE ile veriliyor: büyütülmüş klonun
       kendi gölgesi ve animasyonu !important, onları ezmeye çalışmıyoruz. */
    function sonVezinUyar() {
        var rs = refler();
        if (!rs.length) return;
        var hedef = document.getElementById('crisp-zoom-clone') || kutuBul(rs[rs.length - 1]);
        if (!hedef) return;
        function yak(a) {
            if (a) {
                hedef.style.setProperty('outline', '4px solid rgba(220,53,69,.62)', 'important');
                hedef.style.setProperty('outline-offset', '3px', 'important');
            } else {
                hedef.style.removeProperty('outline');
                hedef.style.removeProperty('outline-offset');
            }
        }
        yak(1);
        setTimeout(function () { yak(0); }, 150);
        setTimeout(function () { yak(1); }, 290);
        setTimeout(function () { yak(0); }, 470);
    }

    /* ---------------------------------------------------------------- */
    /* İLERİ ADIM                                                        */
    /* ---------------------------------------------------------------- */

    /* İLERİ TUŞU = KUTUYA DOKUNMAK. Her basış TEK adım atar, yani tek
       tık sesi çıkar. Kutunun döngüsü:
         büyütme kapalı : 1 kutu seçilir → 2 kök vezne girer (yeşil+anlam)
         büyütme açık   : 1 seçilir → 2 büyür → 3 kök vezne girer → 4 kapanır
       Döngü bitince BİR SONRAKİ basış yeni vezne geçer. */
    function dongusuBitti(kutu) {
        if (!kutu) return true;
        var asama = parseInt(kutu.getAttribute('data-tiklama-sayisi') || '0', 10);
        return asama >= sonAsama();
    }

    function sonAsama() {
        return buyutmeAcik() ? 4 : (mobilMi() ? 1 : 2);
    }

    function ileri() {
        var rs = refler();
        if (!rs.length) return;                       /* kök tanımlı değil: tuş sessiz */

        /* Bir geçiş sürüyorken gelen basış YUTULUR (sıra atlamasın).
           Sekme değişimi bandı 1 sn kaydırıyor; o sırada ikinci basış
           bir vezni görünmeden geçirirdi. */
        if (mesgul) return;

        /* Önce içinde bulunulan veznin adımları biter */
        if (sira >= 0 && sira < rs.length) {
            var simdiki = kutuBul(rs[sira]);
            if (simdiki && !dongusuBitti(simdiki)) {
                if (typeof handleBoxClick === 'function') handleBoxClick(simdiki);
                return;
            }
        }

        /* SON VEZİN: büyütme açık olsun olmasın ilerleme yok */
        if (sira >= rs.length - 1) {
            vezinBittiSesi();
            sonVezinUyar();
            return;
        }
        sira++;
        vezneGit(rs[sira]);
    }

    function vezneGit(ref) {
        var kutu = kutuBul(ref);
        if (!kutu) return;
        mesgul = true;

        if (typeof closeAllZoomedBoxes === 'function') closeAllZoomedBoxes();
        anlamGizle();

        /* Kutu öteki sekmedeyse önce sekmeyi çevir (bant kayması 1 sn sürer) */
        var sekmeDegisti = false;
        if (!mobilMi() && typeof setTab === 'function' && typeof currentTabActive !== 'undefined') {
            if (kutu.closest('#tab1') && currentTabActive !== 0) { setTab(0); sekmeDegisti = true; }
            else if (kutu.closest('#tab2') && currentTabActive !== 1) { setTab(1); sekmeDegisti = true; }
        }

        setTimeout(function () {
            ortala(kutu);
            ilkDokunus(kutu);
        }, sekmeDegisti ? 950 : 0);

        /* Emniyet: bir yerde takılırsa tuş sonsuza dek kilitli kalmasın */
        clearTimeout(bekci);
        bekci = setTimeout(function () { mesgul = false; }, 2600);
    }

    function ortala(kutu) {
        var r = kutu.getBoundingClientRect();
        var orta = window.scrollY + r.top - (window.innerHeight / 2) + (r.height / 2);
        window.scrollTo({ top: Math.max(0, orta), behavior: 'smooth' });
    }

    /* Yeni vezne varılınca YALNIZ TEK dokunuş: kutu seçilir, kelime
       henüz türemez. Eskiden burada arka arkaya iki tık yapılıyordu
       (seç + türet); ikisi 45 ms arayla iki tık SESİ çıkarıyordu ve
       "çift ses" olarak duyuluyordu. Artık her basış tek adım, tek ses. */
    function ilkDokunus(kutu) {
        if (zincir) { clearTimeout(zincir); zincir = null; }
        if (typeof handleBoxClick !== 'function') { mesgul = false; return; }

        /* Daha önce türetilmemiş kutuyu sıfırdan başlat: aşama sayacı
           eski bir ziyaretten kalmış olabilir. */
        if (!kutu.classList.contains('kok-turendi')) kutu.removeAttribute('data-tiklama-sayisi');

        handleBoxClick(kutu);
        mesgul = false;
    }

