    var katman = null, katmanKutu = null, katmanZaman = null, cerceve = null;

    function ekBul(o) {
        if (!o) return null;
        for (var k in o) {
            if (YAPISAL.indexOf(k) !== -1) continue;
            if (o[k] && typeof o[k] === 'object') return o[k].base ? o[k].base : o[k];
        }
        return null;
    }

    /* Sözlükteki örnek cümle(ler): kimi kayıtta tek nesne, kimisinde
       dizi ({ar, tr} ve seyrek olarak {not}). Hepsi diziye çevrilir. */
    function ornekListesi(d) {
        var ham = null;
        if (!d) return [];
        if (d.ornek) ham = d.ornek;
        else if (d.base && d.base.ornek) ham = d.base.ornek;
        else if (d.tekil && d.tekil.base && d.tekil.base.ornek) ham = d.tekil.base.ornek;
        if (!ham) return [];
        var dizi = Array.isArray(ham) ? ham : [ham];
        return dizi.filter(function (o) { return o && (o.ar || o.tr); });
    }

    /* Hızlı Liste hangi metni gösteriyorsa aynı sıra ile okunur */
    function anlamBul(k, ref) {
        var sonuc = { emoji: '', tr: '', ornekler: [] };
        if (typeof sozlukVerileri === 'undefined') return sonuc;
        var kv = sozlukVerileri[k];
        if (!kv) return sonuc;
        var d = kv[ref];
        if (!d) d = kv[String(ref)];
        if (!d) d = kv[parseInt(ref, 10)];
        if (!d) return sonuc;

        if (d.tekil && d.tekil.base) {
            sonuc.emoji = d.tekil.base.emoji || '';
            sonuc.tr = d.tekil.base.trText || '';
        } else if (d.base) {
            sonuc.emoji = d.base.emoji || '';
            sonuc.tr = d.base.trText || d.base.tr || '';
        } else {
            sonuc.emoji = d.emoji || '';
            sonuc.tr = d.trText || d.tr || '';
        }

        /* Temel anlam boşsa ilk "+" ekinin anlamı gösterilir */
        if (!sonuc.tr || !String(sonuc.tr).trim()) {
            var ek = ekBul(d) || (d.tekil ? ekBul(d.tekil) : null);
            if (ek) {
                sonuc.tr = ek.trText || ek.tr || '';
                sonuc.emoji = ek.emoji || sonuc.emoji;
            }
        }
        sonuc.ornekler = ornekListesi(d);
        return sonuc;
    }

