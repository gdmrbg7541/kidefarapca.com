    function ekBul(o) {
        if (!o) return null;
        for (var k in o) {
            if (YAPISAL.indexOf(k) !== -1) continue;
            if (o[k] && typeof o[k] === 'object') return o[k].base ? o[k].base : o[k];
        }
        return null;
    }

    /* "+" EKİ UYGULANMIŞSA O EKİN KENDİ KAYDI OKUNUR.
       Kutuya ek eklenince ana betik kutuya data-active-suffix yazıyor
       ve sözlükte o eke ait ayrı bir kayıt varsa kelimeyi ona göre
       değiştiriyor (ör. عِلْم + ال). Anlam da o kaydın anlamı olmalı.
       Anahtar eşleştirmesi harekeler ve tatvil atılarak yapılıyor:
       sözlükteki anahtar ile kutudaki ekin hareke SIRASI farklı olsa
       bile (ي+üstün+şedde / ي+şedde+üstün) ikisi de eşleşir. */
    function ciplak(t) {
        return String(t || '')
            .replace(/[\u200B-\u200D\uFEFF]/g, '')
            .replace(/[\u06CC\u0649]/g, '\u064A')      /* farsça ye / elif maksure -> ye */
            .replace(/[\u0640\u064B-\u0652]/g, '')     /* tatvil ve harekeler */
            .trim();
    }

    function ekKaydi(d, aktifEk) {
        if (!d || !aktifEk) return null;
        if (d[aktifEk] && typeof d[aktifEk] === 'object') return d[aktifEk];
        var hedef = ciplak(aktifEk);
        if (!hedef) return null;
        var bul = function (aranan) {
            for (var a in d) {
                if (YAPISAL.indexOf(a) !== -1) continue;
                if (!d[a] || typeof d[a] !== 'object') continue;
                if (ciplak(a) === aranan) return d[a];
            }
            return null;
        };
        var s1 = bul(hedef);
        if (s1) return s1;
        /* Ana betikteki karşılıklar: "ية" kaydı yoksa "ة", "يات" yoksa "ات" */
        if (hedef === '\u064A\u0629') return bul('\u0629');
        if (hedef === '\u064A\u0627\u062A') return bul('\u0627\u062A');
        return null;
    }

    /* Sözlükteki örnek cümle(ler): kimi kayıtta tek nesne, kimisinde
       dizi ({ar, tr} ve seyrek olarak {not}). Hepsi diziye çevrilir. */
    function ornekListesi(d) {
        var ham = null;
        if (!d) return [];
        if (d.ornek) ham = d.ornek;
        else if (d.base && d.base.ornek) ham = d.base.ornek;
        else if (d.tekil && d.tekil.base && d.tekil.base.ornek) ham = d.tekil.base.ornek;
        if (!ham) return [];
        var dizi = Array.isArray(ham) ? ham : [ham];
        return dizi.filter(function (o) { return o && (o.ar || o.tr); });
    }

    /* Hızlı Liste hangi metni gösteriyorsa aynı sıra ile okunur */
    function anlamBul(k, ref, aktifEk) {
        var sonuc = { emoji: '', tr: '', ornekler: [] };
        if (typeof sozlukVerileri === 'undefined') return sonuc;
        var kv = sozlukVerileri[k];
        if (!kv) return sonuc;
        var d = kv[ref];
        if (!d) d = kv[String(ref)];
        if (!d) d = kv[parseInt(ref, 10)];
        if (!d) return sonuc;

        /* Kutuda bir "+" eki etkinse önce onun karşılığı */
        var ek = ekKaydi(d, aktifEk);
        var ekTemel = (ek && ek.base) ? ek.base : ek;
        if (ekTemel && (ekTemel.trText || ekTemel.tr)) {
            sonuc.emoji = ekTemel.emoji || '';
            sonuc.tr = ekTemel.trText || ekTemel.tr || '';
            sonuc.ornekler = ornekListesi(ek);
            return sonuc;
        }

        if (d.tekil && d.tekil.base) {
            sonuc.emoji = d.tekil.base.emoji || '';
            sonuc.tr = d.tekil.base.trText || '';
        } else if (d.base) {
            sonuc.emoji = d.base.emoji || '';
            sonuc.tr = d.base.trText || d.base.tr || '';
        } else {
            sonuc.emoji = d.emoji || '';
            sonuc.tr = d.trText || d.tr || '';
        }

        /* Temel anlam boşsa ilk "+" ekinin anlamı gösterilir */
        if (!sonuc.tr || !String(sonuc.tr).trim()) {
            var ek = ekBul(d) || (d.tekil ? ekBul(d.tekil) : null);
            if (ek) {
                sonuc.tr = ek.trText || ek.tr || '';
                sonuc.emoji = ek.emoji || sonuc.emoji;
            }
        }
        sonuc.ornekler = ornekListesi(d);
        return sonuc;
    }

