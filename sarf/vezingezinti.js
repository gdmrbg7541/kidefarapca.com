    /* Türkçe anlamın punto merdiveni — hepsi ~%10 büyütüldü. */
    var YAN_PUNTO = [70, 62, 53, 46, 40, 34];
    var SOL_PAY = 0.028;          /* dev kutunun sol kenarına bırakılan pay */
    var ARA = 30;                 /* kutu ile anlam paneli arası */
    var SAG_PAY = 24;             /* panelin sağ kenar payı */
    var PANEL_YUK_UST = 620;      /* panelin en fazla boyu */

    /* KUTU DOĞDUĞU ANDA, SABİT ÖLÇÜSÜYLE, SOLDA AÇILIR.
       Kutunun eni eskiden içindeki kelimeye göreydi: vezin (فَعِلَ) ile
       türemiş kelime (عَلِمَ) aynı enle yazılmadığı için kök vezne
       girince kutu büyüyüp küçülüyordu — "esneme". Artık kutunun eni
       de boyu da sabit: en = ekranın %45'i, boy = tam puntonun satır
       yüksekliği + kutu payları.
       Sözlükteki 4617 tek kelimelik yazılışın en genişi 180 punto ile
       587 px; %45'lik kutunun iç genişliğine sığmayan yaklaşık %1'lik
       uzun kelimede KUTU değil YAZI biraz küçülür, kutu yerinde kalır.
       ANLAM kapalıysa hiç dokunmuyoruz: kutu eskisi gibi ortada,
       kendi eniyle açılır. */
    /* Vezin kutusunun ekran eni. 0,45'ten 0,40'a indirildi: kutudan
       kısılan yer anlam paneline gidiyor, panel yatayda ~%10 genişliyor
       (Geylani: "anlam kısmını yatay olarak %10 daha büyük yap"). */
    var EN_ORANI = 0.40;
    var TAM_PUNTO = 0;
    var olcer = null;

    function yaz(el, ozellik, deger) {           /* değişmiyorsa yazma */
        if (!el || el.style.getPropertyValue(ozellik) === deger) return;
        el.style.setProperty(ozellik, deger, 'important');
    }

    /* Yazı enini gizli bir ölçekle alıyoruz: klonun kendi ölçüsü açılış
       animasyonunun ölçeğinden etkilendiği için güvenilmez. */
    function metinEni(metin, punto) {
        if (!olcer) {
            olcer = document.createElement('span');
            olcer.style.cssText = 'position:fixed;left:-99999px;top:0;visibility:hidden;' +
                "white-space:nowrap;font-family:'Arakom',sans-serif;font-weight:normal;line-height:1.2";
            document.body.appendChild(olcer);
        }
        olcer.style.fontSize = punto + 'px';
        olcer.textContent = metin;
        return olcer.getBoundingClientRect().width;
    }

    function klonaSigdir(klon, icEn) {
        var yazi = klon.querySelector('.ar, .ar-small');
        if (!yazi) return;
        if (!TAM_PUNTO) TAM_PUNTO = parseFloat(window.getComputedStyle(yazi).fontSize) || 180;
        var gerekli = metinEni(String(yazi.textContent || '').trim(), TAM_PUNTO) * 1.02;
        if (gerekli > icEn) {
            yaz(yazi, 'font-size', Math.max(80, Math.floor(TAM_PUNTO * icEn / gerekli)) + 'px');
        } else if (yazi.style.fontSize) {
            yazi.style.removeProperty('font-size');
        }
    }

    function klonuSolaCek(klon) {
        if (!klon || !anlamAcik()) return 0;
        var vw = window.innerWidth;
        var sabitEn = Math.round(vw * EN_ORANI);
        var h = window.getComputedStyle(klon);
        var yanPay = parseFloat(h.paddingLeft) + parseFloat(h.paddingRight) +
                     parseFloat(h.borderLeftWidth) + parseFloat(h.borderRightWidth);
        var dikPay = parseFloat(h.paddingTop) + parseFloat(h.paddingBottom) +
                     parseFloat(h.borderTopWidth) + parseFloat(h.borderBottomWidth);
        if (!isFinite(yanPay)) yanPay = 118;
        if (!isFinite(dikPay)) dikPay = 78;

        if (!TAM_PUNTO) {
            var y = klon.querySelector('.ar, .ar-small');
            if (y) TAM_PUNTO = parseFloat(window.getComputedStyle(y).fontSize) || 180;
        }
        yaz(klon, 'width', sabitEn + 'px');
        yaz(klon, 'min-width', sabitEn + 'px');
        yaz(klon, 'max-width', sabitEn + 'px');
        /* Boy da sabit: uzun kelimede yazı küçülse bile kutu alçalmasın */
        yaz(klon, 'min-height', Math.round(dikPay + (TAM_PUNTO || 180) * 1.2) + 'px');
        klonaSigdir(klon, sabitEn - yanPay);

        var solKenar = Math.max(36, vw * SOL_PAY);
        var merkez = Math.round(solKenar + sabitEn / 2);
        yaz(klon, 'left', merkez + 'px');
        yaz(document.getElementById('crisp-root-clone'), 'left', merkez + 'px');
        return merkez;
    }

    /* Klon gövdeye eklenir eklenmez yerine otursun: zamanlayıcıyla
       yakalanırsa önce ortada bir kare görünüp sonra sola sıçrıyor. */
    var klonGozcu = null;
    function klonIzle() {
        if (klonGozcu || !document.body || typeof MutationObserver !== 'function') return;
        klonGozcu = new MutationObserver(function (kayitlar) {
            for (var i = 0; i < kayitlar.length; i++) {
                var eklenen = kayitlar[i].addedNodes;
                for (var j = 0; j < eklenen.length; j++) {
                    var n = eklenen[j];
                    if (!n || n.nodeType !== 1) continue;
                    if (n.id === 'crisp-zoom-clone') {
                        klonuSolaCek(n);
                    } else if (n.id === 'crisp-root-clone') {
                        var z = document.getElementById('crisp-zoom-clone');
                        if (z && z.style.left) n.style.setProperty('left', z.style.left, 'important');
                    }
                }
            }
        });
        klonGozcu.observe(document.body, { childList: true });
    }

    /* TİTREME OLMASIN DİYE: yerleşim yalnız GERÇEKTEN değişince
       hesaplanıyor. Eskiden 400 ms'lik yoklama her turda punto denemesi
       yapıp ölçü alıyordu; sınırdaki metinlerde iki punto arasında
       gidip gelebiliyor, kutu da açılış animasyonu sürerken ölçüldüğü
       için katman oynuyordu. Artık ölçüler DÜZEN değerlerinden
       (offsetWidth/Height, hesaplanmış top) alınıyor ve imza aynıysa
       hiçbir stil yazılmıyor. */
    var yanIz = '';

    function yanaYerlestir(klon) {
        var vw = window.innerWidth, vh = window.innerHeight;
        var merkez = klonuSolaCek(klon);
        if (!merkez) return false;

        var en = klon.offsetWidth || 0;
        var merkezY = parseFloat(window.getComputedStyle(klon).top);
        if (!isFinite(merkezY)) merkezY = vh * 0.35;

        var sol = Math.round(merkez + en / 2 + ARA);
        var panelEn = Math.round(vw - sol - SAG_PAY);
        if (panelEn < 240) return false;              /* yer yok: alta düş */

        var kutuYuk = klon.offsetHeight || 290;
        var kutuUst = Math.round(merkezY - kutuYuk / 2);
        /* Panel BOYU da sabit: örnekler sığmazsa panel uzamaz, örnek
           alanı kendi içinde kayar. Üst kenarı dev kutuyla aynı hizada
           başlar, aşağıda ekran payına kadar iner. */
        var orneksiz = katman.classList.contains('vg-orneksiz');
        var panelYuk = orneksiz ? kutuYuk : Math.round(Math.max(kutuYuk,
            Math.min(PANEL_YUK_UST, vh - kutuUst - 24)));

        var iz = [vw, vh, en, sol, panelEn, panelYuk, kutuUst, katman.textContent].join('|');
        if (iz === yanIz && katman.classList.contains('vg-yan')) return true;
        yanIz = iz;

        katman.classList.add('vg-yan');
        katman.style.removeProperty('pointer-events');
        katman.classList.remove('vg-alt', 'vg-ust', 'vg-buyuk');
        /* EN ve BOY SABİT: panel her vezinde aynı dikdörtgen. Böylece
           anlam değişince ne panel ne de dev kutu yer/ölçü değiştirir. */
        katman.style.width = panelEn + 'px';
        katman.style.maxWidth = panelEn + 'px';
        katman.style.height = panelYuk + 'px';
        katman.style.minHeight = panelYuk + 'px';

        /* Punto ANLAMIN kendi boyuna göre seçilir: örnek varsa panelin
           yarısını, yoksa panelin tamamını aşmayan en büyük punto.
           Örnekler sığmazsa yazı KÜÇÜLTÜLMEZ — gövde kendi içinde
           kayar. (Aksi hâlde örneği çok olan kelimede anlam gereksiz
           yere en küçük puntoya düşüyordu.) */
        var bas = katman.querySelector('.vg-bas');
        var sinir = orneksiz ? panelYuk - 44 : panelYuk * 0.46;
        for (var i = 0; i < YAN_PUNTO.length; i++) {
            katman.style.fontSize = YAN_PUNTO[i] + 'px';
            if (!bas || bas.offsetHeight <= sinir) break;
        }

        var ust = Math.round(Math.max(12, Math.min(kutuUst, vh - panelYuk - 12)));
        katman.style.left = sol + 'px';
        katman.style.top = ust + 'px';

        /* Örnekler sığmıyorsa alt kenar yumuşasın: devamı olduğu
           anlaşılsın, kesilmiş gibi durmasın. */
        var gv = katman.querySelector('.vg-govde');
        katman.classList.toggle('vg-kayar', !!gv && gv.scrollHeight > gv.clientHeight + 2);
        /* Ok, dev kelimenin ortasını göstersin */
        var okY = Math.max(24, Math.min(merkezY - ust, panelYuk - 24));
        katman.style.setProperty('--vg-oky', Math.round(okY) + 'px');
        return true;
    }

    /* Katman, ekranda GÖRÜNEN öğeye yapışır: kutu büyütülmüşse dev
       klona, değilse kutunun kendisine. */
    function konumla() {
        if (!katman || !katman.classList.contains('vg-acik')) return;
        if (!katmanKutu || !katmanKutu.isConnected || perdeAcikMi()) { anlamGizle(); return; }

        var klon = document.getElementById('crisp-zoom-clone');
        if (klon && yanaYerlestir(klon)) return;

        /* Kutu yatayda ekran dışına çıktıysa (sekme bandı kaydı, öteki
           sekmeye geçildi) katman havada kalmasın. */
        var kr = katmanKutu.getBoundingClientRect();
        var kx = kr.left + kr.width / 2;
        if (kx < -8 || kx > window.innerWidth + 8) { anlamGizle(); return; }

        katman.classList.remove('vg-yan');
        katman.style.fontSize = '';
        katman.style.width = '';
        katman.style.maxWidth = '';
        katman.style.height = '';
        katman.style.minHeight = '';
        yanIz = '';
        var hedef = klon || katmanKutu;
        katman.classList.toggle('vg-buyuk', !!klon);

        var r = hedef.getBoundingClientRect();
        if (!r.width && !r.height) { anlamGizle(); return; }

        var o = katman.getBoundingClientRect();
        var bosluk = klon ? 22 : 14;
        var altta = r.bottom + bosluk + o.height <= window.innerHeight - 8;
        var ust = altta ? (r.bottom + bosluk) : (r.top - bosluk - o.height);

        katman.classList.toggle('vg-alt', altta);
        katman.classList.toggle('vg-ust', !altta);

        var sol = r.left + r.width / 2 - o.width / 2;
        sol = Math.max(8, Math.min(sol, window.innerWidth - o.width - 8));
        katman.style.top = Math.max(8, ust) + 'px';
        katman.style.left = sol + 'px';

        /* Ok, kutunun ortasını göstersin (katman kenara dayandıysa kayar) */
        var okX = r.left + r.width / 2 - sol;
        okX = Math.max(18, Math.min(okX, o.width - 18));
        katman.style.setProperty('--vg-okx', (okX - 9) + 'px');
    }

    function izlemeyeBasla() {
        if (cerceve !== null) return;
        window.addEventListener('scroll', tazele, true);
        window.addEventListener('resize', tazele);
        cerceve = 1;
        katmanZaman = setInterval(function () {
            if (!katman || !katman.classList.contains('vg-acik')) return;
            konumla();
        }, 400);
    }

    function izlemeyiDurdur() {
        if (cerceve === null) return;
        window.removeEventListener('scroll', tazele, true);
        window.removeEventListener('resize', tazele);
        cerceve = null;
        if (katmanZaman) { clearInterval(katmanZaman); katmanZaman = null; }
    }

    var bekleyen = false;
    function tazele() {
        if (bekleyen) return;
        bekleyen = true;
        requestAnimationFrame(function () { bekleyen = false; konumla(); });
    }

