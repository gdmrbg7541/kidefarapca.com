    var zincir = null;      /* açık tıklama zincirinin zamanlayıcısı */
    var mesgul = false;     /* geçiş sürüyor: yeni basışlar yutulur */
    var bekci = null;       /* kilit takılırsa açan emniyet zamanlayıcısı */

    /* ---------------------------------------------------------------- */
    /* KÜÇÜK YARDIMCILAR                                                */
    /* ---------------------------------------------------------------- */

    function mobilMi() { return window.innerWidth <= 1024; }

    function buyutmeAcik() {
        if (mobilMi()) return false;
        var c = document.getElementById('zoomToggleCheckbox');
        return !!(c && c.checked);
    }

    function anlamAcik() {
        var c = document.getElementById('anlamToggleCheckbox');
        return !!(c && c.checked);
    }

    function kok() {
        var k = (typeof currentRoot !== 'undefined' && currentRoot) ? String(currentRoot).trim() : '';
        if (k.length !== 3) return '';
        if (typeof sozlukVerileri === 'undefined' || !sozlukVerileri[k]) return '';
        return k;
    }

    function refler() {
        var k = kok();
        if (!k) return [];
        if (typeof getSortedRefsForRoot !== 'function') return [];
        return getSortedRefsForRoot(k) || [];
    }

    function refOku(kutu) {
        if (!kutu) return '';
        var r = kutu.querySelector('.ref');
        var t = r ? String(r.textContent || '').trim() : '';
        if (!t) t = kutu.getAttribute('data-ref') || '';
        return t;
    }

    function kutuBul(ref) {
        var hedef = String(ref).trim();
        var kapsam = mobilMi() ? '#mobile-grid .glass-box' : '.window-pencere .glass-box';
        var liste = Array.prototype.slice.call(document.querySelectorAll(kapsam));
        for (var i = 0; i < liste.length; i++) {
            if (refOku(liste[i]) === hedef) return liste[i];
        }
        return null;
    }

    function dizinBul(rs, ref) {
        var hedef = String(ref).trim();
        for (var i = 0; i < rs.length; i++) {
            if (String(rs[i]).trim() === hedef) return i;
        }
        return -1;
    }

    /* Perdelerin bir kısmı display, bir kısmı opacity/pointer-events ile
       gizleniyor (ör. #sarfOyunlarOverlay hep "block" durur, yalnız
       .open sınıfıyla görünür). O yüzden görünürlük hesaplanan stilden
       okunuyor. Sonuç 150 ms önbelleklenir: tuş basışı ve konumlama
       aynı anda sormasın. */
    function gorunurMu(el) {
        if (!el) return false;
        var h = window.getComputedStyle(el);
        if (!h) return false;
        if (h.display === 'none' || h.visibility === 'hidden') return false;
        if (parseFloat(h.opacity || '1') < 0.05) return false;
        return el.getClientRects().length > 0;
    }

    var perdeSon = 0, perdeDurum = false;
    function perdeAcikMi() {
        var simdi = Date.now();
        if (simdi - perdeSon < 150) return perdeDurum;
        perdeSon = simdi;
        perdeDurum = true;
        /* Bâb odağı / kalıp odağı üst çubuğu kilitler */
        if (document.body && document.body.classList.contains('ust-kilit')) return true;
        if (window.isAtlasMode) return true;
        for (var i = 0; i < PERDELER.length; i++) {
            if (gorunurMu(document.getElementById(PERDELER[i]))) return true;
        }
        perdeDurum = false;
        return false;
    }

    /* Klavyeden yazı yazılıyor mu / gezinti kapalı mı */
    function gezintiKapali() {
        if (perdeAcikMi()) return true;
        if (window.BabOdak && typeof window.BabOdak.aktif === 'function' && window.BabOdak.aktif()) return true;
        if (window.KalipOdak && typeof window.KalipOdak.aktif === 'function' && window.KalipOdak.aktif()) return true;
        var a = document.activeElement;
        if (a && (a.tagName === 'INPUT' || a.tagName === 'TEXTAREA' || a.isContentEditable)) return true;
        return false;
    }

