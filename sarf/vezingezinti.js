    var ILERI_TUSLARI = ['ArrowRight', 'PageDown', ' ', 'Spacebar'];
    var GERI_TUSLARI = ['ArrowLeft', 'PageUp', 'Backspace'];

    /* Sözlük kaydında "+ eki" sayılmayan (yapısal) anahtarlar */
    var YAPISAL = ['base', 'cekimi', 'isNotVerb', 'ornek', 'tekil', 'cogul',
                   'isDictOnly', 'tip', 'cogulTr', 'suggestsPlus',
                   'hasZamirCekimi', 'zamirBase', 'autoGenerated',
                   'isHiddenInList', 'cogulId', 'tekilId', 'not',
                   'kuralliCogul', 'emoji', 'tekilTr'];

    /* Tam ekranı kaplayan katmanlar: bunlardan biri açıkken anlam
       katmanı görünmez (üstlerine binmesin). */
    var PERDELER = ['keyboard-overlay', 'marathon-overlay', 'marathon-countdown-overlay',
                    'fast-dictionary-overlay', 'verb-overlay', 'conjugation-overlay',
                    'bab-info-overlay', 'aksam-info-overlay', 'aksam-sema-overlay',
                    'telaffuz-overlay', 'sarfOyunlarOverlay', 'ek-bilgi-perde',
                    'kt-kilavuz', 'rootOfDayOverlay', 'fdm-yukleniyor'];

