    let activeSet = [], currentStage = 0, startTime, timerInterval, elapsedTime = 0, isPaused = false, raceMode = false, errorMemory = new Set(), selectedBap = "";

    function init() {
        const container = document.getElementById('bap-list');
        baps.forEach(b => {
            const btn = document.createElement('button');
            btn.className = 'bap-btn'; btn.innerText = b;
            btn.onclick = () => { sfx(600,'sine',0.05); selectedBap = b; showFiils(b); };
            container.appendChild(btn);
        });
    }

    function showFiils(bap) {
        hideHeaderElements(); 
        const container = document.getElementById('fiil-list');
        container.innerHTML = '';
        verbs[bap].forEach(f => {
            const btn = document.createElement('button');
            btn.className = 'fiil-btn'; btn.innerText = f;
            btn.onclick = () => { sfx(600,'sine',0.05); preparePlay(f); };
            container.appendChild(btn);
        });
        showScreen('screen-fiil');
    }

    function hideHeaderElements() {
        document.getElementById('stage-label').classList.remove('ui-visible');
        document.getElementById('chrono-main').style.display = 'none';
        document.getElementById('pause-btn').classList.remove('ui-visible');
        document.getElementById('timer-display').classList.remove('ui-visible');
        document.getElementById('live-total-score').classList.remove('ui-visible');
    }

    function preparePlay(fiil) {
    // BURASI KRİTİK: Eğer fiil verbData içinde varsa listeyi al, yoksa eski usul devam et
    if (verbData && verbData[fiil]) {
        activeSet = verbData[fiil];
    } else {
        activeSet = Array(36).fill(fiil); 
    }
    
    currentStage = 0; 
    errorMemory.clear(); 
    elapsedTime = 0; 
    raceMode = false;
    showScreen('screen-play'); 
    loadTable();
    
    // UI güncellemeleri
    document.getElementById('stage-label').classList.add('ui-visible');
    document.getElementById('chrono-main').style.display = 'block';
    document.getElementById('chrono-main').classList.remove('active');
}

    function handleChronoClick() {
        if (!raceMode) {
            raceMode = true;
            document.getElementById('chrono-main').classList.add('active');
            document.getElementById('overlay').style.display = 'flex';
            document.getElementById('start-btn-ui').style.display = 'block';
            document.getElementById('countdown-text').style.display = 'none';
        } else { resetRace(); }
    }

function startCountdown() {
    errorMemory.clear(); 
    currentStage = 0; 
    loadTable();
    document.getElementById('start-btn-ui').style.display = 'none';
    const cd = document.getElementById('countdown-text');
    cd.style.display = 'block';
    let count = 3; 
    cd.innerText = count;

    // 'const interval' yerine yukarıda tanımladığımız 'countInterval'ı kullanıyoruz
    countInterval = setInterval(() => {
        count--;
        if (count > 0) { 
            cd.innerText = count; 
            sfx(400, 'sine', 0.1); 
        } else { 
            clearInterval(countInterval); // Sayım bittiğinde temizle
            document.getElementById('overlay').style.display = 'none'; 
            startTimer(); 
        }
    }, 1000);
}

    function startTimer() {
        document.getElementById('pause-btn').classList.add('ui-visible');
        document.getElementById('timer-display').classList.add('ui-visible');
        document.getElementById('live-total-score').classList.add('ui-visible');
        startTime = Date.now();
        timerInterval = setInterval(() => {
            if (!isPaused) {
                elapsedTime = (Date.now() - startTime) / 1000;
                document.getElementById('timer-display').innerText = elapsedTime.toFixed(2);
                let score = Math.max(0, Math.round(100 - (elapsedTime > 45 ? (elapsedTime-45)*2 : 0) - (errorMemory.size * 2)));
                document.getElementById('live-total-score').innerText = score;
            }
        }, 50);
    }

    function loadTable() {
    const table = document.getElementById('table-view');
    table.innerHTML = '';
    
    // Sayfa aralıkları: Mazi: 0-15, Muzari: 15-30, Emir: 30-36
    const ranges = [[0, 15], [15, 30], [30, 36]];
    const start = ranges[currentStage][0];
    const end = ranges[currentStage][1];
    
    document.getElementById('stage-label').innerText = ["MAZİ", "MUZARİ", "EMİR"][currentStage];

    // Sadece ilgili sayfadaki fiilleri gösterir
    activeSet.slice(start, end).forEach((w, i) => {
        const absoluteIdx = start + i;
        const div = document.createElement('div');
        div.className = 'cell ' + (Math.floor(i/3) % 2 === 0 ? 'muez-row' : 'mue-row');
        div.innerText = w;
        
        div.onclick = function() {
            if (errorMemory.has(absoluteIdx)) {
                errorMemory.delete(absoluteIdx);
                this.classList.remove('error-active');
            } else {
                errorMemory.add(absoluteIdx);
                this.classList.add('error-active');
            }
        };
        table.appendChild(div);
    });

    // Navigasyon butonları
    document.getElementById('prev-arr').disabled = (currentStage === 0);
    const rArr = document.getElementById('next-arr');
    rArr.innerText = (currentStage === 2) ? "✓" : "❯";
}

    function changeStage(dir) {
        if (currentStage === 2 && dir === 1 && raceMode) { finishRace(); return; }
        currentStage += dir;
        loadTable();
    }

    function finishRace() {
        clearInterval(timerInterval);
        document.getElementById('final-score').innerText = document.getElementById('live-total-score').innerText;
        document.getElementById('final-stats').innerText = `${elapsedTime.toFixed(2)} Saniye | ${errorMemory.size} Hata`;
        
        const errList = document.getElementById('error-list');
        errList.innerHTML = '';
        errorMemory.forEach(idx => {
            const item = document.createElement('div');
            item.className = 'error-item'; item.innerText = activeSet[idx];
            errList.appendChild(item);
        });

        showScreen('screen-result');
        hideHeaderElements();
    }

   function resetToFiilSelection() { 
        // 1. Önce kronometreyi ve zaman değişkenlerini sıfırla
        clearInterval(timerInterval);
        elapsedTime = 0;
        startTime = 0;
        isPaused = false;
        
        const timerDisplay = document.getElementById('timer-display');
        if(timerDisplay) timerDisplay.textContent = "00:00";

        // 2. Fiil seçim ekranını görsel olarak aktif et (Kritik adım)
        showScreen('screen-fiil'); 
        
        // 3. Seçili kategoriye ait fiilleri listele
        showFiils(selectedCat); 
    }

    function resetRace() { 
        raceMode = false; 
        clearInterval(timerInterval); 
        elapsedTime = 0; // Yarış sıfırlandığında süreyi de sıfırla
        hideHeaderElements(); 
        loadTable(); 
    }

    function togglePause() { 
        isPaused = !isPaused; 
        if (!isPaused) {
            // Duraklatmadan çıkınca süreyi kaldığı yerden devam ettir
            startTime = Date.now() - (elapsedTime * 1000);
        }
    }
    
function goBack() {
    // 1. Devam eden bir geri sayım (3-2-1) varsa iptal et
    if (countInterval) {
        clearInterval(countInterval);
    }

    // 2. Devam eden bir kronometre (0.01...) varsa iptal et
    if (timerInterval) {
        clearInterval(timerInterval);
    }

    // 3. UI Elementlerini gizle
    const overlay = document.getElementById('overlay');
    if (overlay) overlay.style.display = 'none';
    
    hideHeaderElements();
    raceMode = false;
    document.getElementById('chrono-main').classList.remove('active');

    // 4. Ekran yönlendirmesi
    const active = document.querySelector('.screen.active').id;
    if (active === 'screen-play') {
        resetToFiilSelection();
    } else if (active === 'screen-fiil') {
        showScreen('screen-bap');
    } else {
        window.location.href = "kaliplartablosu.html";
    }
}

    function showScreen(id) {
        document.querySelectorAll('.screen').forEach(s => s.classList.remove('active'));
        document.getElementById(id).classList.add('active');
        
        // Navigasyon oklarının görünürlük kontrolü
        const arrows = document.querySelectorAll('.nav-arrow');
        if (id === 'screen-play') {
            arrows.forEach(a => a.style.display = 'block');
        } else {
            arrows.forEach(a => a.style.display = 'none');
        }
    }

