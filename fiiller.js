    function switchTab(e, name) {
        document.querySelectorAll('.tab-panel').forEach(p => p.classList.remove('active'));
        document.querySelectorAll('.tab-link').forEach(l => l.classList.remove('active'));
        document.getElementById(name).classList.add('active');
        e.currentTarget.classList.add('active');
    }

    function init() {
        const key = document.getElementById("verbSelector").value;
        const v = verbsData[key];

        // MAZİ TABLOSU
        let mHtml = "";
        for(let r=0; r<5; r++){
            mHtml += `<tr class="${maziMuzariRowClasses[r]}">`;
            for(let c=0; c<3; c++){
                let idx = r*3 + c;
                let fullWord = v.mazi[idx];
                let mean = mPats[idx].m.replace("#", v.trMean.mazi);
                mHtml += createTd(mPats[idx].p, fullWord, mean);
            }
            mHtml += "</tr>";
        }
        document.getElementById("maziBody").innerHTML = mHtml;

        // MUZARİ TABLOSU
        let muzHtml = "";
        for(let r=0; r<5; r++){
            muzHtml += `<tr class="${maziMuzariRowClasses[r]}">`;
            for(let c=0; c<3; c++){
                let idx = r*3 + c;
                let fullWord = v.muzari[idx];
                let mean = muzPats[idx].m.replace("#", v.trMean.muzari);
                muzHtml += createTd(muzPats[idx].p, fullWord, mean);
            }
            mHtml += "</tr>";
        }
        document.getElementById("muzariBody").innerHTML = muzHtml;

        // EMİR TABLOSU
        let eHtml = `<tr class="row-muzekker">`;
        for(let c=0; c<3; c++) {
            let fullWord = v.emir[c];
            let mean = ePats[c].m.replace("#", v.trMean.emir);
            eHtml += createTd(ePats[c].p, fullWord, mean);
        }
        eHtml += `</tr><tr class="row-muennes">`;
        for(let c=3; c<6; c++) {
            let fullWord = v.emir[c];
            let mean = ePats[c].m.replace("#", v.trMean.emir);
            eHtml += createTd(ePats[c].p, fullWord, mean);
        }
        document.getElementById("emirBody").innerHTML = eHtml + "</tr>";
    }

    function createTd(p, f, a) {
        return `<td onclick="this.classList.toggle('active-cell')">
            <span class="pattern arabic">${p}</span>
            <span class="full arabic">${f}</span>
            <span class="meaning">${a}</span>
        </td>`;
    }

