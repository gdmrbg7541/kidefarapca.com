    // --- VERİ DÖNÜŞTÜRÜCÜ VE SENARYO HAZIRLAYICI ---
    function generateScenarios(data) {
        const gameScenarios = [];

        Object.keys(data).forEach(root => {
            const verbData = data[root];

            // 1. Tabloları Oluştur (5x3 ve 2x3 formatı)
            const maziTable = [
                verbData.mazi.slice(0, 3), // Müfred, Tesniye, Cemi
                verbData.mazi.slice(3, 6),
                verbData.mazi.slice(6, 9),
                verbData.mazi.slice(9, 12),
                [verbData.mazi[12], verbData.mazi[13], verbData.mazi[13]]
            ];

            const muzariTable = [
                verbData.muzari.slice(0, 3),
                verbData.muzari.slice(3, 6),
                verbData.muzari.slice(6, 9),
                verbData.muzari.slice(9, 12),
                [verbData.muzari[12], verbData.muzari[13], verbData.muzari[13]]
            ];

            const emirTable = [
                verbData.emir.slice(0, 3),
                verbData.emir.slice(3, 6)
            ];

            // 2. Rastgele Bir Hedef Kelime Seç (Soru)
            // Tüm kelimeler havuzu
            const allForms = [...verbData.mazi, ...verbData.muzari, ...verbData.emir];
            
            // Hedef kelime olarak KÖK kelimeyi hariç tutuyoruz (ki soru direk cevap olmasın)
            // Soru: Yektubu -> Cevap: Ketebe olsun.
            const possibleTargets = allForms.filter(word => word !== root);
            const target = possibleTargets.length > 0 
                ? possibleTargets[Math.floor(Math.random() * possibleTargets.length)] 
                : root;

            // 3. DOĞRU CEVAP: Her zaman KÖK kelime (Mazi 1. Hücre)
            const correctAnswer = root; 

            // 4. Şıkları Oluştur (Doğru Cevap + 4 Yanıltıcı)
            let options = new Set();
            options.add(correctAnswer); // Doğru cevabı ekle

            // Yanıltıcıları ekle (Aynı fiilin diğer çekimlerinden seçelim)
            while(options.size < 5) {
                const randomDistractor = allForms[Math.floor(Math.random() * allForms.length)];
                options.add(randomDistractor);
            }

            // Senaryoyu ekle
            gameScenarios.push({
                root: root,           // Kök (Doğru Cevap)
                target: target,       // Soru (Görünen kelime)
                tables: {
                    mazi: maziTable,
                    muzari: muzariTable,
                    emir: emirTable
                },
                opts: Array.from(options)
            });
        });

        // Karıştır
        return gameScenarios.sort(() => Math.random() - 0.5);
    }

    // --- OYUN DEĞİŞKENLERİ ---
    let scenarios = [];
    let currentIdx = 0;

    // --- TABLO HTML OLUŞTURUCU ---
    function generateTableHTML(dataRows, type, targetWord) {
        let html = `<table class="verb-table">
            <tr>
                <th>Müfred</th>
                <th>Tesniye</th>
                <th>Cemi</th>
            </tr>`;
        
        dataRows.forEach((row, rowIndex) => {
            html += "<tr>";
            row.forEach((word, colIndex) => {
                let cellClass = "";
                
                // Buzlu Hücre: SADECE Mazi tablosunun ilk hücresi (Kök/Cevap)
                if(type === 'mazi' && rowIndex === 0 && colIndex === 0) {
                    cellClass = "frozen-cell";
                }

                // Vurgulu Hücre: Aranan (Sorulan) kelime
                if (word === targetWord) {
                    cellClass += " highlight-cell";
                }

                if (cellClass.includes("frozen-cell")) {
                    html += `<td class="${cellClass}" data-clicks="0" onclick="crackIce(this)">${word}</td>`;
                } else {
                    html += `<td class="${cellClass}">${word}</td>`;
                }
            });
            html += "</tr>";
        });
        html += "</table>";
        return html;
    }

    // --- OYUN YÖNETİMİ ---
    function loadScenario() {
        if (scenarios.length === 0) {
            scenarios = generateScenarios(rawVerbs);
        }

        const data = scenarios[currentIdx];

        // 1. Soru Gösterimi (Target)
        document.getElementById('target-word-display').innerText = data.target;
        
        const optsArea = document.getElementById('options-area');
        optsArea.innerHTML = "";
        
        // 2. Şıkları Karıştır
        const shuffledOpts = [...data.opts].sort(() => Math.random() - 0.5);
        
        shuffledOpts.forEach(opt => {
            const btn = document.createElement('button');
            btn.className = 'det-opt-btn';
            btn.innerText = opt;
            // DİKKAT: Artık data.root (kök kelime) ile karşılaştırıyoruz
            btn.onclick = () => checkAnswer(opt, data.root, btn); 
            optsArea.appendChild(btn);
        });

        // 3. Tabloları Yükle
        document.getElementById('table-mazi-area').innerHTML = generateTableHTML(data.tables.mazi, 'mazi', data.target);
        document.getElementById('table-muzari-area').innerHTML = generateTableHTML(data.tables.muzari, 'muzari', data.target);
        document.getElementById('table-emir-area').innerHTML = generateTableHTML(data.tables.emir, 'emir', data.target);

        // 4. İpucu Dosyasını Aç (Vurgulu kelime neredeyse orayı aç)
        closeAllPanels();
        let foundType = null;
        if (checkIfWordInTable(data.tables.mazi, data.target)) foundType = 'mazi';
        else if (checkIfWordInTable(data.tables.muzari, data.target)) foundType = 'muzari';
        else if (checkIfWordInTable(data.tables.emir, data.target)) foundType = 'emir';

        if (foundType) toggleTable(foundType);
    }

    function checkIfWordInTable(tableData, word) {
        return tableData.some(row => row.includes(word));
    }

    // --- ARAYÜZ ---
    function toggleTable(type) {
        const content = document.getElementById(`content-${type}`);
        const btn = document.getElementById(`btn-${type}`);
        const isOpen = content.classList.contains('open');

        closeAllPanels();

        if (!isOpen) {
            content.classList.add('open');
            btn.classList.add('active');
        }
    }

    function closeAllPanels() {
        document.querySelectorAll('.accordion-content').forEach(el => el.classList.remove('open'));
        document.querySelectorAll('.accordion-btn').forEach(el => el.classList.remove('active'));
    }

    function crackIce(element) {
        let clicks = parseInt(element.getAttribute('data-clicks') || 0);
        clicks++;
        if (clicks === 1) element.classList.add('crack-1');
        else if (clicks === 2) element.classList.add('crack-2');
        element.setAttribute('data-clicks', clicks);
    }

    function checkAnswer(selected, correct, btnElement) {
        if (selected === correct) {
            btnElement.style.background = "#00b894";
            btnElement.style.color = "white";
            btnElement.style.borderColor = "#00b894";
            setTimeout(() => {
                currentIdx++;
                if (currentIdx < scenarios.length) loadScenario();
                else { 
                    alert("Harika! Tüm kökleri buldun. Oyun yeniden başlıyor."); 
                    currentIdx = 0;
                    scenarios = generateScenarios(rawVerbs);
                    loadScenario(); 
                }
            }, 1000);
        } else {
            btnElement.style.background = "#ff7675";
            btnElement.style.color = "white";
            btnElement.style.borderColor = "#d63031";
            btnElement.disabled = true;
        }
    }

    window.onload = loadScenario;