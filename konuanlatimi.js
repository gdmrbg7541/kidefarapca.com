    function openVerb(verb) {
        currentVerb = verb;
        const data = verbData[verb];
        if(!data) return;

        document.getElementById('modal-root').innerText = verb;
        document.getElementById('modal-meaning').innerText = data.meaning;
        document.getElementById('verbModal').style.display = 'flex';
        
        switchTab('mazi'); // Varsayılan sekme
    }

    function closeModal(e) {
        if(e.target.classList.contains('modal-overlay')) {
            document.getElementById('verbModal').style.display = 'none';
        }
    }

    function closeModalDirect() {
        document.getElementById('verbModal').style.display = 'none';
    }

