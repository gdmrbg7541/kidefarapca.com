/* Veri dosyaları yüklenmemişse (ör. index.html bu dosyayı yalnızca
   educationData için yükler) boş iskeletle çalışılır. */
var _KALIP = window.KIDEF_KALIP || { ad: 'Kalıp İfadeler', gruplar: [], konular: [] };
var _ALAN  = window.KIDEF_ALAN  || { ad: 'Alan Konuları',  gruplar: [], konular: [] };

/* konular dizisini "id -> konu" haritasına çevirir */
function _harita(veri) {
    var m = {};
    (veri.konular || []).forEach(function (k) { m[k.id] = k; });
    return m;
}
var _kalipH = _harita(_KALIP);
var _alanH  = _harita(_ALAN);

/* Başlıkta oynatılacak içerik var mı? (kelime / cümle / diyalog) */
function _doluMu(k) {
    if (!k) return false;
    return !!((k.words && k.words.length) ||
              (k.sentence && k.sentence.length) ||
              (k.dialog && k.dialog.length));
}

/* Doğrudan oynatıcıya giden kategori üretir — ünite kartı YOKTUR.
   Başlığa tıklandığında  muhadese.html?ders=<kat>_<id>  açılır ve
   oradaki giriş panelinde KELİMELER / CÜMLE / DİYALOG tuşları çıkar. */
function _dogrudanKat(id, ad, alt, ikon, veri, harita) {
    return {
        id: id, ad: ad, alt: alt, ikon: ikon,
        dogrudan: true,
        ipucu: 'Bir başlığa dokun: kelimeler, cümle ve diyalog pratiği açılır',
        anahtarlar: function () { return (veri.konular || []).map(function (k) { return k.id; }); },
        etiket: function (k) { return harita[k] || { ad: k, ar: '' }; },
        hazir: function (k) { return _doluMu(harita[k]); },
        baglanti: function (k) {
            return 'muhadese.html?ders=' + id + '_' + encodeURIComponent(k) +
                   '&kaynak=liste&kat=' + id + '&konu=' + encodeURIComponent(k);
        },
        uniteler: function () { return []; },
        gruplar: (veri.gruplar && veri.gruplar.length ? veri.gruplar : [{ id: 'genel', baslik: '' }])
            .map(function (g) {
                return {
                    baslik: g.baslik,
                    esle: function (k) {
                        var t = harita[k];
                        return !!t && (t.grup || 'genel') === g.id;
                    }
                };
            })
    };
}

