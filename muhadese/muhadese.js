/* Sekme tanımları */
const KATEGORILER = [
    {
        id: 'okul', ad: 'Okul', alt: '5 – 10. Sınıf', ikon: MUH_IKON.okul,
        dogrudan: false,
        ipucu: 'Turkuaz olanları kullanabilirsiniz',
        anahtarlar: function () { return Object.keys(educationData); },
        etiket: function (k) { return { ad: k + '. Sınıf', ar: '' }; },
        uniteler: function (k) { return educationData[k] || []; },
        hazir: function (k) {
            return (educationData[k] || []).some(function (u) {
                return (u.lessons || []).some(function (d) { return d.aktif; });
            });
        },
        gruplar: [{ baslik: '', esle: function () { return true; } }]
    },
    _dogrudanKat('kalip', 'Kalıp İfadeler', 'Bol örnekli', MUH_IKON.kalip, _KALIP, _kalipH),
    _dogrudanKat('alan',  'Alan Konuları',  'Sağlık, tarih, felsefe…', MUH_IKON.alan, _ALAN, _alanH)
];

function _kat(id) {
    for (var i = 0; i < KATEGORILER.length; i++) if (KATEGORILER[i].id === id) return KATEGORILER[i];
    return KATEGORILER[0];
}
/* Bir konuda kullanıma hazır içerik var mı? */
function _hazirMi(kat, anahtar) { return kat.hazir(anahtar); }

var _seciliKat = 'okul';
var _seciliAnahtar = null;

/* ---------------- SEKMELER ---------------- */
function renderSekmeler() {
    var kutu = document.getElementById('kat-sekme');
    if (!kutu) return;
    kutu.innerHTML = '';
    KATEGORILER.forEach(function (kat) {
        var b = document.createElement('button');
        b.className = 'kat-btn' + (kat.id === _seciliKat ? ' active' : '');
        b.type = 'button';
        b.setAttribute('data-kat', kat.id);
        b.innerHTML = '<span class="kat-ikon" aria-hidden="true">' + kat.ikon + '</span>' +
                      '<span class="kat-yazi"><span class="kat-ad">' + kat.ad + '</span>' +
                      '<span class="kat-alt">' + kat.alt + '</span></span>';
        b.onclick = function () { kategoriSec(kat.id, true); };
        kutu.appendChild(b);
    });
}

function kategoriSec(katId, kullaniciSecti) {
    _seciliKat = katId;
    try { localStorage.setItem('muhKategori', katId); } catch (e) { }
    renderSekmeler();
    var kat = _kat(katId);
    var kayitli = null;
    try { kayitli = localStorage.getItem('muhSon_' + katId); } catch (e) { }
    var liste = kat.anahtarlar();
    var secilecek = (kayitli && liste.indexOf(kayitli) !== -1) ? kayitli : liste[0];
    renderSecici(kat, secilecek, kullaniciSecti);
}

/* ---------------- KONU / SINIF SEÇİCİ ---------------- */
function renderSecici(kat, anahtar, kullaniciSecti) {
    var kutu = document.getElementById('class-buttons');
    if (!kutu) return;
    kutu.innerHTML = '';
    var tumu = kat.anahtarlar();

    /* Başlık altındaki küçük ipucu kategoriye göre değişir.
       Okul sekmesinde yeşil ders yoksa hiç gösterilmez. */
    var not = document.querySelector('.header-note');
    if (not) {
        var varMi = tumu.some(function (k) { return _hazirMi(kat, k); });
        not.textContent = kat.ipucu;
        not.style.display = (kat.dogrudan || varMi) ? '' : 'none';
    }

    kat.gruplar.forEach(function (g) {
        var uyeler = tumu.filter(g.esle);
        if (!uyeler.length) return;
        var grupKutu = document.createElement('div');
        grupKutu.className = 'secici-grup';
        if (g.baslik) {
            var bas = document.createElement('span');
            bas.className = 'grup-baslik';
            bas.innerText = g.baslik;
            grupKutu.appendChild(bas);
        }
        var sira = document.createElement('div');
        sira.className = 'grup-sira';
        uyeler.forEach(function (k) {
            var e = kat.etiket(k);
            var hazir = _hazirMi(kat, k);
            var ic = '<span class="kb-ad">' + e.ad + '</span>' +
                     (e.ar ? '<span class="kb-ar">' + e.ar + '</span>' : '');
            var btn;

            if (kat.dogrudan) {
                /* Ünite yok: başlık doğrudan oynatıcıya götürür.
                   İçeriği hazır olmayan başlık pasif kalır. */
                if (hazir) {
                    btn = document.createElement('a');
                    btn.className = 'class-btn dogrudan hazir-sinif';
                    btn.href = kat.baglanti(k);
                } else {
                    btn = document.createElement('span');
                    btn.className = 'class-btn dogrudan pasif';
                    btn.setAttribute('aria-disabled', 'true');
                    ic += '<span class="kb-rozet">yakında</span>';
                }
            } else {
                btn = document.createElement('button');
                btn.type = 'button';
                btn.className = 'class-btn' + (hazir ? ' hazir-sinif' : '');
                btn.onclick = function () { konuSec(kat, k, true); };
            }

            btn.setAttribute('data-anahtar', k);
            btn.innerHTML = ic;
            sira.appendChild(btn);
        });
        grupKutu.appendChild(sira);
        kutu.appendChild(grupKutu);
    });

    if (kat.dogrudan) {
        /* Ünite yok; yalnızca son bakılan başlık işaretlenir (derse dönünce
           kullanıcı nerede kaldığını görsün diye). */
        _seciliAnahtar = anahtar;
        document.querySelectorAll('#class-buttons .class-btn').forEach(function (b) {
            b.classList.toggle('active', b.getAttribute('data-anahtar') === anahtar);
        });
        try { localStorage.setItem('muhSon_' + kat.id, anahtar); } catch (e) { }
        renderIcerik(kat, anahtar);
        if (kullaniciSecti) window.scrollTo({ top: headerHeight(), behavior: 'smooth' });
    } else {
        konuSec(kat, anahtar, kullaniciSecti);
    }
}

function konuSec(kat, anahtar, kullaniciSecti) {
    _seciliAnahtar = anahtar;
    try {
        localStorage.setItem('muhSon_' + kat.id, anahtar);
        if (kat.id === 'okul') localStorage.setItem('lastSelectedClass', anahtar);
    } catch (e) { }

    document.querySelectorAll('#class-buttons .class-btn').forEach(function (b) {
        b.classList.toggle('active', b.getAttribute('data-anahtar') === anahtar);
    });

    renderIcerik(kat, anahtar);
    if (kullaniciSecti) window.scrollTo({ top: headerHeight(), behavior: 'smooth' });
}

/* ---------------- ÜNİTE / DERS LİSTESİ ---------------- */
function renderIcerik(kat, anahtar) {
    var container = document.getElementById('unit-container');
    if (!container) return;
    container.innerHTML = '';

    /* Doğrudan kategorilerde ünite kartı yok; yalnızca kısa bir yönlendirme */
    if (kat.dogrudan) {
        container.innerHTML =
            '<div class="dogrudan-bilgi">' +
                '<p class="db-yazi">Yukarıdaki başlıklardan birine dokun; o başlığın ' +
                'çalışma sayfası açılır.</p>' +
                '<div class="db-modul">' +
                    '<span class="db-kart"><span class="db-ikon" aria-hidden="true">' + MUH_IKON.kelime + '</span>Kelimeler</span>' +
                    '<span class="db-kart"><span class="db-ikon" aria-hidden="true">' + MUH_IKON.cumle + '</span>Cümle Pratiği</span>' +
                    '<span class="db-kart"><span class="db-ikon" aria-hidden="true">' + MUH_IKON.diyalog + '</span>Diyalog Pratiği</span>' +
                '</div>' +
            '</div>';
        return;
    }

    var uniteler = kat.uniteler(anahtar);
    if (!uniteler.length) {
        container.innerHTML = '<div class="bos-uyari">Bu başlık için içerik hazırlanıyor.</div>';
        return;
    }

    uniteler.forEach(function (unit) {
        var unitCard = document.createElement('div');
        unitCard.className = 'unit-card';

        var lessonsHTML = (unit.lessons || []).map(function (lesson) {
            var nameSpan = lesson.name
                ? '<span class="lesson-name">' + lesson.name + '</span>'
                : '<span class="lesson-name" style="display:none"></span>';

            var tus;
            if (lesson.aktif && lesson.simultaneUrl) {
                /* Ders bu listeden açıldı: geri tuşu listeye (ve bu başlığa) dönsün. */
                var dersUrl = lesson.simultaneUrl + '&kaynak=liste&kat=' + encodeURIComponent(kat.id) +
                              '&konu=' + encodeURIComponent(anahtar) +
                              (kat.id === 'okul' ? '&sinif=' + encodeURIComponent(anahtar) : '');
                tus = '<a href="' + dersUrl + '" class="action-btn btn-basla hazir">' +
                      '<span class="bas-ok" aria-hidden="true"></span><span class="bas-yz">BAŞLA</span></a>';
            } else {
                tus = '<span class="action-btn btn-yakinda" aria-disabled="true">YAKINDA</span>';
            }

            return '<div class="lesson-item">' +
                       '<div class="lesson-info">' + nameSpan + '</div>' +
                       '<div class="btn-group">' + tus + '</div>' +
                   '</div>';
        }).join('');

        unitCard.innerHTML = '<div class="unit-header">' + unit.unitName + '</div>' +
                             '<div class="lesson-list">' + lessonsHTML + '</div>';
        container.appendChild(unitCard);
    });
}

function headerHeight() {
    var h = document.querySelector('header');
    return (h ? h.offsetHeight : 0) - 50;
}

/* ---------------- BAŞLAT ---------------- */
function muhBaslat() {
    /* Bu dosya index.html'de yalnızca VERİ kaynağı (educationData) olarak da
       yüklenir; orada #class-buttons yoktur, sessizce çıkılır. */
    if (!document.getElementById('class-buttons')) return;

    var p = new URLSearchParams(location.search);
    var katP = p.get('kat') || '';
    var konuP = p.get('konu') || '';
    var sinifP = p.get('sinif') || '';

    /* 1) Adres çubuğundan gelen istek  2) en son bakılan yer  3) varsayılan */
    if (!katP && sinifP && educationData[sinifP]) { katP = 'okul'; konuP = sinifP; }
    if (!katP) { try { katP = localStorage.getItem('muhKategori') || 'okul'; } catch (e) { katP = 'okul'; } }

    var kat = _kat(katP);
    _seciliKat = kat.id;
    renderSekmeler();

    var liste = kat.anahtarlar();
    var anahtar = (konuP && liste.indexOf(konuP) !== -1) ? konuP : null;
    if (!anahtar) {
        try { anahtar = localStorage.getItem('muhSon_' + kat.id); } catch (e) { }
    }
    if (!anahtar || liste.indexOf(anahtar) === -1) {
        anahtar = (kat.id === 'okul' && liste.indexOf('10') !== -1) ? '10' : liste[0];
    }
    renderSecici(kat, anahtar, false);
}

muhBaslat();
